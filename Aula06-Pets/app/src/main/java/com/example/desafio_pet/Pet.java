package com.example.desafio_pet;

public class Pet {
    private String nome;
    private String raca;
    private String cor;
    private int idade;
    private int data_de_aniversario;

    public Pet(String nome, String raca, String cor, int idade, int data_de_aniversario){
        this.nome = nome;
        this.raca = raca;
        this.cor = cor;
        this.idade = idade;
        this.data_de_aniversario = data_de_aniversario;
    }

}
