package com.example.projetoaula06_pets;

public class Pet {
    public String nome;
    public String cor;
    public String raca;
    public int idade;
    public int niver;

    public Pet(String nome,String cor,String raca, int idade, int niver)
    {
        this.nome = nome;
        this.cor = cor;
        this.raca = raca;
        this.idade = idade;
        this.niver = niver;
    }
}


