package com.example.aula06_pet;

public class Pet {
    public String nome;
    public String cor;
    public String raca;
    public String idade;
    public String aniversario;

    public Pet(String nome, String cor, String raca, String idade, String aniversario) {
        this.nome = nome;
        this.cor = cor;
        this.raca = raca;
        this.idade = idade;
        this.aniversario = aniversario;
    }
}
